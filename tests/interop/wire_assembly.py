#!/usr/bin/env python3
"""Fresh bounded UF/HF plaintext-wire captures at an owned TLS-terminating fixture.

Both TLS hops verify the same disposable receiver identity. Captures are original
HTTP S2S entities or decrypted compact TCP streams, never parser-generated bytes.
"""
