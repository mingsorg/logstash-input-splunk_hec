MAXIMUM=64<<20
HANDSHAKE_TIMEOUT=3

class FiniteTLS:
    """Handshake in the owned handler thread, never in the listening accept loop."""
    def finish_request(self,request,address):
        request.settimeout(HANDSHAKE_TIMEOUT)
        try:
            with self.tls_context.wrap_socket(request,server_side=True,do_handshake_on_connect=False) as secured:
                secured.do_handshake()
                secured.settimeout(60)
                super().finish_request(secured,address)
        except (TimeoutError,ssl.SSLError,OSError):
            request.close() # stalled/reset clients are bounded fixture failures, not capture payloads

class Capture:
    def __init__(self,rt,transport,row):
        self.rt=rt;self.transport=transport;self.row=row;self.lock=threading.Lock();self.items=[];self.stopped=threading.Event()
        self.directory=runtime.EVIDENCE/'wire-assembly'/uuid.uuid4().hex
        self.directory.mkdir(parents=True)
        self.temporary=tempfile.TemporaryDirectory(dir=rt['directory'])
        key=Path(self.temporary.name)/'key.pem'
        command=['openssl','pkcs12','-in',str(rt['directory']/'state/identity/server.p12'),'-passin',
                 'file:'+str(rt['directory']/'state/identity/password'),'-nocerts','-nodes','-out',str(key)]
        try:
            subprocess.run(command,check=True,capture_output=True,timeout=30);key.chmod(0o600)
            context=ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
            context.load_cert_chain(str(rt['directory']/'state/identity/server.crt'),str(key))
            owner=self
            if transport=='http':
                class Handler(BaseHTTPRequestHandler):
                    def request(self):
                        self.connection.settimeout(60)
                        length=int(self.headers.get('Content-Length','0'))
                        if not 0<=length<=MAXIMUM or self.headers.get('Transfer-Encoding'):
                            self.send_error(400);return
                        payload=self.rfile.read(length)
                        if len(payload)!=length:self.send_error(400);return
                        connection=http.client.HTTPSConnection('localhost',rt['port'],context=rt['context'],timeout=60)
                        try:
                            headers={k:v for k,v in self.headers.items() if k.lower() not in ('host','content-length','connection')}
                            connection.request(self.command,self.path,payload,headers)
                            response=connection.getresponse();body=response.read()
                            if payload and '/s2s' in self.path:
                                owner.retain(payload,'http-entity',{'method':self.command,'path':self.path.split('?')[0],'receiver_status':response.status})
                            self.send_response(response.status);self.send_header('Content-Type','application/json');self.send_header('Content-Length',str(len(body)))
                            self.send_header('Connection','close');self.end_headers();self.wfile.write(body)
                        finally:connection.close()
                    do_POST=do_GET=request
                    def log_message(self,*args):pass
                class Server(FiniteTLS,ThreadingHTTPServer):pass
                self.server=Server(('0.0.0.0',0),Handler)
                self.server.daemon_threads=False
            else:
                class Server(FiniteTLS,socketserver.ThreadingTCPServer):
                    allow_reuse_address=True
                    daemon_threads=False
                class Handler(socketserver.BaseRequestHandler):
                    def handle(self):
                        upstream=rt['context'].wrap_socket(socket.create_connection(('127.0.0.1',rt['tcp_port']),timeout=30),server_hostname='localhost')
                        client=self.request
                        for peer in (client,upstream):peer.settimeout(1)
                        buffers={'client':bytearray(),'server':bytearray()};errors=[]
                        def pump(source,destination,direction):
                            try:
                                while not owner.stopped.is_set():
                                    try:data=source.recv(65536)
                                    except socket.timeout:continue
                                    if not data:break
                                    if len(buffers[direction])+len(data)>MAXIMUM:raise RuntimeError('wire capture budget exhausted')
                                    buffers[direction].extend(data);destination.sendall(data)
                            except (OSError,ssl.SSLError):pass # native peers close/reset during teardown
                            except Exception as error:errors.append(error_details(error))
                            finally:
                                try:destination.shutdown(socket.SHUT_WR)
                                except OSError:pass
                        reverse=threading.Thread(target=pump,args=(upstream,client,'server'))
                        reverse.start()
                        try:pump(client,upstream,'client');reverse.join(10)
                        finally:
                            upstream.close();client.close();reverse.join(5)
                        if reverse.is_alive():errors.append({'type':'CleanupError','message':'capture pump still owned'})
                        for direction,payload in buffers.items():
                            if payload:owner.retain(bytes(payload),'tcp-'+direction,{'errors':errors})
                self.server=Server(('0.0.0.0',0),Handler)
            self.server.tls_context=context
            self.port=self.server.server_address[1]
            self.thread=threading.Thread(target=self.server.serve_forever);self.thread.start()
        except Exception:
            self.temporary.cleanup();raise
    def retain(self,payload,kind,metadata):
        digest=hashlib.sha256(payload).hexdigest();name=kind+'-'+digest+'.bin'
        with self.lock:
            (self.directory/name).write_bytes(payload)
            self.items.append({'file':str((self.directory/name).relative_to(runtime.ROOT)),'sha256':digest,'bytes':len(payload),'kind':kind,**metadata})
    def close(self):
        self.stopped.set();self.server.shutdown();self.server.server_close();self.thread.join(10);self.temporary.cleanup()
        assert not self.thread.is_alive()
        assert self.items and all(not row.get('errors') for row in self.items),self.items
        self.row['wire_capture']={'authority':'fresh TLS-terminating fixture capture; original transport bytes, not reconstructed records',
                                  'items':self.items,'bounded_bytes_per_direction':MAXIMUM}

def main():
    report={'artifact':runtime.artifact_info(),'validators':runtime.validators_info(),'runs':[],'status':'fail'};rt=None;capture=None
    try:
        flags,host=sender_network()
        with socket.socket() as available:available.bind(('127.0.0.1',0));port=available.getsockname()[1]
        rt=runtime.start_tcp_runtime('latest',tls=True,queue='persisted',tcp_port=port,hec_metadata='full',
                                     s2s_metadata_fields=assembly.MAPPING,s2s_line_breaker_rules=assembly.RULES)
        for transport in ('http','tcp'):
            for role in ('uf','hf'):
                row={'sender':role,'transport':transport,'status':'fail'};report['runs'].append(row)
                capture=Capture(rt,transport,row)
                forwarded=dict(rt)
                forwarded['port' if transport=='http' else 'tcp_port']=capture.port
                assembly.real_sender(forwarded,role,transport,'full',flags,host,row)
                capture.close();capture=None
        assert runtime.artifact_info()==report['artifact'];report['status']='pass'
    except Exception as error:report['error']=error_details(error)
    finally:
        if capture is not None:
            try:capture.close()
            except Exception as error:report.setdefault('cleanup_errors',[]).append(error_details(error))
        if rt is not None:finish_receiver(rt,report,diagnostics=report['status']!='pass')
        if report.get('cleanup_errors'):report['status']='fail'
        (runtime.EVIDENCE/'wire-assembly.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
    if report['status']!='pass':print(report.get('error',{}),file=sys.stderr)
    return 0 if report['status']=='pass' else 1

if __name__=='__main__':sys.exit(main())
